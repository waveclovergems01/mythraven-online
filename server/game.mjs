import 'dotenv/config';
import sharp from 'sharp';
import {fileURLToPath} from 'node:url';
import {Server} from '@colyseus/core';
import {WebSocketTransport} from '@colyseus/ws-transport';
import {TerrainRoom,configureTerrainWorld} from './terrain-room.mjs';
import {buildTerrainData} from '../shared/terrain-data.mjs';
import {localPorts} from './local-ports.mjs';
const server=new Server({transport:new WebSocketTransport(),greet:false});
const shoreline=await sharp(fileURLToPath(new URL('../public/assets/maps/mythraven-land.png',import.meta.url))).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const terrainData=buildTerrainData({data:shoreline.data,width:shoreline.info.width,height:shoreline.info.height});
configureTerrainWorld(terrainData);
server.define('mythraven-world',TerrainRoom);
server.define('mythraven-west-march',TerrainRoom);
const port=localPorts(process.env).game;
await server.listen(port,'127.0.0.1');
console.log(`Colyseus local game server: ws://127.0.0.1:${port}`);
